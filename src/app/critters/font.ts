export function bitmap(ch: string) {
  return G[ch] ?? G['?'];
}

/** The glyph's lit pixels, turned by quarter turns, as offsets inside the cell. */
export function pixels(ch: string, turn: 0 | 1 | 2 | 3): [number, number][] {
  const rows = bitmap(ch);
  const w = Math.max(...rows.map(r => r.length)), h = rows.length;
  const out: [number, number][] = [];
  rows.forEach((row, y) => Array.from(row).forEach((c, x) => {
    if (c !== '#') return;
    // Centre the glyph in the cell, then turn it about the centre.
    const dx = x - (w - 1) / 2, dy = y - (h - 1) / 2;
    const [rx, ry] = turn === 0 ? [dx, dy] : turn === 1 ? [-dy, dx] : turn === 2 ? [-dx, -dy] : [dy, -dx];
    out.push([Math.round(rx + (CELL_W - 1) / 2 - .01), Math.round(ry + (CELL_H - 2) / 2)]);
  }));
  return out;
}
